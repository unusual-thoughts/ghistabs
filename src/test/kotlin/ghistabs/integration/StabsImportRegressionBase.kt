    @Test
    @ExpectedToFail(
        fixtures = [
            "crypto_mi_test_gcc421.exe", "crypto_mi_test_gcc421_stripped.exe",
            "xmltest_gcc421.exe", "xmltest_gcc421_stripped.exe",
            // a.out: both fixtures are plain C, so there are no classes and no vtables at all.
            "hello_aout_gcc295.o", "zlib_aout_gcc263.o",
            // C++, but gcc 2.95's minimal-debug `##` method encoding fails the class body, and its
            // vtables are pre-Itanium `__vt_9TiXmlNode` symbols rather than `_ZTV` regardless.
            "tinyxml_aout_gcc295.o",
        ],
        reason = "gcc 12 omits the method stab section for polymorphic classes, so no vftable is applied",
    )
    fun atLeastOneVtableStructApplied() {
        // box2d_tests shows no detectable C++ surface (no mangled symbols, no `_vptr`, no virtuals);
        // xmltest is C++ but gcc 12 omits the method section from the stab for every polymorphic
        // class (XMLNode et al.) — same Pattern-B family as the other gcc 12 missing-stab issues.
        // Surface via println so future fixture changes regain coverage without flagging the run.
        //
        // The applied vtable struct is the `<Class>_vftable` (the function-pointer array laid at the
        // address point); there is no separate `<Class>_vtable` full-record struct — the
        // offset_to_top + rtti header words are plain Data before the address point.
        val vftables = filledVftables()
        if (binaryName in setOf("box2d_tests", "xmltest")) {
            println("atLeastOneVtableStructApplied[$binaryName/$mode]: vftables=${vftables.size}")
            return
        }
        vftables.mustNotBeEmpty("Expected at least one *_vftable struct with components")
        // A derived class inherits its vfptr through its `_base_<Parent>` subobject, so most carry
        // no pointer directly — but the root of every chain must, or ClassBuilder's vfptr insertion
        // is broken end to end.
        val backEdges = vftables.count { vft ->
            program.dataTypeManager.allDataTypes.asSequence()
                .filterIsInstance<Structure>()
                .filter { it.name == vft.name.removeSuffix("_vftable") }
                .any { cls -> cls.components.any { (it.dataType as? Pointer)?.dataType === vft } }
        }

        backEdges.must(
            "Expected ≥ 1 *_vftable to have a back-edge {vfptr} from its class; got $backEdges / ${vftables.size}",
        ) { this >= 1 }
        // Every slot is a pointer to the function definition its own field is named for.
        val badSlots = vftables.flatMap { it.components.asIterable() }
            .filter { (it.dataType as? Pointer)?.dataType?.name != it.fieldName }
