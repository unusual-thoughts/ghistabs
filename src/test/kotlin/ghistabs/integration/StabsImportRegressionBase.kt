    /**
     * Every class as it was actually built: the canonical group's *winner* body paired with the
     * Structure that body produced.
     *
     * Not `harvest.types`, which is every ast a CU ever emitted. A group folds definitions that
     * disagree, and pairing a loser's body with `dataTypeFor` compares two different declarations —
     * cryptopp defines `InvalidKeyLength` eight times (`Exception` in two CUs, `InvalidArgument` in
     * six) and `tagMONITORINFOEXA` both flat and derived, so a layout assertion driven that way
     * reports gcc's inconsistency as our defect.
     */
    private fun builtClasses(): List<Pair<TypeDecl.Struct<GlobalTypeId>, Structure>> =
        artifacts.index.byLocation.values.mapNotNull { located ->
            val body = located.type.body as? TypeDecl.Struct ?: return@mapNotNull null
            (artifacts.registry.dataTypeFor(located.type.id) as? Structure)?.let { body to it }
        }

    /** Every `<Class>_vftable` that got slots, one copy per name (the fullest). */
    private fun filledVftables() = program.dataTypeManager.allDataTypes.asSequence()
        .filterIsInstance<Structure>().filter { it.name.endsWith("_vftable") }
        .groupBy { it.name }.values.map { copies -> copies.maxBy { it.numComponents } }
        .filter { it.numComponents > 0 }

    /** The Ghidra function for each `STATIC`-flagged method the stabs name, keyed by linkage name.
     *  The Cygwin PE loader prefixes symbols with `_`, so both spellings are tried. */
    private fun staticMethodsByMangledName(): Map<String, Function> = artifacts.harvest.types.values
        .mapNotNull { it.asStruct() }
        .flatMap { (_, body) -> body.methods.filter { it.virt == VirtKind.STATIC }.mapNotNull { it.mangled } }
        .distinct()
        .mapNotNull { mangled ->
            sequenceOf(mangled, "_$mangled")
                .mapNotNull { program.symbolTable.getSymbols(it).firstOrNull() }
                .firstNotNullOfOrNull { program.functionManager.getFunctionAt(it.address) }
                ?.let { mangled to it }
        }.toMap()

    /** The gas idiom at [at]: `eb <n>` then n NOPs, landing on a 16-byte boundary. */
    private fun jumpOverFillAt(bytes: ByteArray, at: Int, blockStart: Long): Boolean {
        val skip = bytes.getOrNull(at + 1)?.toInt() ?: return false
        val end = at + 2 + skip
        return bytes[at] == 0xeb.toByte() &&
            skip in 1..14 &&
            end <= bytes.size &&
            (blockStart + end) % 16 == 0L &&
            (at + 2 until end).all { bytes[it] == 0x90.toByte() }
    }

    /** Whether a base contributes bytes. An empty class is `sizeof == 1` and the empty-base
     *  optimization drops it from the layout entirely; member *functions* do not make it occupy
     *  space, so [TypeDecl.Struct.hasMembers] is the wrong question here. */
    private fun occupiesSpace(base: TypeDecl<GlobalTypeId>) =
        (resolve(base) as? TypeDecl.Struct)?.let { it.sizeBytes > 1 } == true

    /** A [TypeDecl.Ref] followed to the harvest body it names; anything else unchanged. */
    private fun resolve(type: TypeDecl<GlobalTypeId>): TypeDecl<GlobalTypeId> =
        (type as? TypeDecl.Ref)?.let { artifacts.harvest.types[it.id]?.body } ?: type

    private val harvestsStdString
        get() = artifacts.harvest.types.values.any { it.ghidraName.startsWith("basic_string<") }

    private fun wordAt(a: Address): Long? = runCatching {
        if (program.defaultPointerSize == 8) program.memory.getLong(a) else program.memory.getInt(a).toLong()
    }.getOrNull()

    /** Whether the pointer stored at [a] targets executable memory — how the address point is told
     *  apart from the rtti / vbase-offset words in front of it. */
    private fun pointsIntoCode(a: Address) = wordAt(a)
        ?.takeIf { it != 0L }
        ?.let { program.addressFactory.defaultAddressSpace.getAddress(it) }
        ?.let { program.memory.getBlock(it)?.isExecute } == true

    /**
     * The function-relative address heuristic ([ghistabs.GenericAddressResolver.stabAddress]): every `N_SLINE`/`N_LBRAC`/`N_RBRAC`
     * record, resolved against its enclosing `N_FUN`, must land in executable memory. A value left
     * un-rebased resolves to a tiny address in no code block. Not asserted against the *enclosing*
     * function specifically — gcc clones ctors/dtors, so a stab function's line range legitimately
     * spans sibling clones. Runs on every fixture. (Folded from the former
     * FuncRelativeAddressIntegrationTest.)
     */
    @Test
    @ExpectedToFail(
        fixtures = ["zlib_aout_gcc263.o"],
        reason = "relocatable object (ld -r): sections all sit at 0 unrelocated, so stab values " +
            "cannot resolve into executable code",
    )
    fun funcRelativeAddressesLandInExecutableCode() {
        val resolver = program.defaultContext().resolver
        val reader = StabReader.fromProgram(program)
        assumeTrue(reader != null, "no .stab in $binaryName")

        var funcStart: Address? = null
        var checked = 0
        val notCode = mutableListOf<String>()
        for (rec in reader!!.physicalRecords()) {
            when (rec.type) {
                StabType.N_FUN ->
                    funcStart = rec.name.ifEmpty { null }?.let { resolver.buildAddress(rec.value) }

                StabType.N_SLINE, StabType.N_LBRAC, StabType.N_RBRAC -> {
                    val fs = funcStart ?: continue
                    val target = resolver.stabAddress(rec.value, fs)
                    checked++
                    if (program.memory.getBlock(target)?.isExecute != true) {
                        notCode += "${rec.type} @${rec.index} value=0x${rec.value.toString(16)} → $target (from $fs)"
                    }
                }

                else -> {}
            }
        }
        assumeTrue(checked > 0, "no func-relative records in $binaryName")
        notCode.mustBeEmpty(
            "func-relative stab values resolved outside executable code in $binaryName " +
                "(${notCode.size}/$checked):\n${notCode.take(20).joinToString("\n")}",
        )
    }
