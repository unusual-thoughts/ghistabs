            "${padded.size} of ${classes.size} classes carry bytes past their last described field",
        )

        // A single base at +0 is the *same* Structure instance as the base class, not a same-sized
        // synthetic standing in for it — that is what the truncate-at-placeholder-creation ordering
        // buys, and holding an ancestor instead means the base loop resolved the wrong link.
        //
        val synthetic = builtClasses().mapNotNull { (body, dt) ->
            val base = body.bases.singleOrNull()
                ?.takeIf { it.offsetBits == 0L && !it.isVirtual && occupiesSpace(it.type) }
                ?: return@mapNotNull null
            val baseType = (base.type as? TypeDecl.Ref)?.id?.let { artifacts.registry.dataTypeFor(it) }
                ?: return@mapNotNull null
            val field = dt.components.firstOrNull { Itanium.isBaseField(it.fieldName.orEmpty()) }
                ?: return@mapNotNull null
            "${dt.name}: base field is ${field.dataType.pathName}, base class is ${baseType.pathName}"
                .takeUnless { field.offset == 0 && field.dataType === baseType }
        }
        synthetic.take(10).mustBeEmpty(
            "${synthetic.size} single-base classes hold a stand-in rather than the base Structure itself",
        )
    }

    /**
     * FillerByteAnalyzer is the only source of [AlignmentDataType] in the pipeline, so a nonzero
     * count is exactly its hits. Runs on every fixture.
     * (Folded from the former FillerByteAnalyzerIntegrationTest — rides on setUp's autoanalysis.)
     */
    @Test
    fun fillerBytesCollapsedToAlignment() {
        assumeTrue { mode != Mode.BEFORE }
        val data = program.listing.getDefinedData(true)
        var runs = 0
        while (data.hasNext()) if (data.next().dataType is AlignmentDataType) runs++
        runs.must("FillerByteAnalyzer collapsed no padding in $binaryName") { this > 0 }
    }

    /**
     * The GAS jump-over-fill idiom must collapse too, not just plain NOP runs: an unconditional
     * forward JMP over the padding to the aligned boundary, NOPs behind it (`eb 0d 90…`). gas emits
     * it wherever the padded region is reachable by fallthrough, so the Alignment has to start on
     * the JMP opcode — otherwise the jump disassembles as live code in front of the padding.
     *
     * The sites are found by scanning the bytes for the idiom, independently of the listing the
     * analyzer wrote — so this is a cross-check of `FillerByteAnalyzer`, not a restatement of it.
     *
     * Padding *between* functions only. gas emits the same three bytes for `-falign-loops` inside a
     * live function body (box2d has 17 of those and no other kind), where the JMP is reached by
     * fallthrough and is the function's own control flow: collapsing it to data would punch a hole
     * through the instruction stream and cost the enclosing function its decompilation. Nothing the
     * analyzer should touch, so nothing this should demand.
     */
    @Test
    fun jumpOverFillCollapsedToAlignment() {
        assumeTrue { mode != Mode.BEFORE }
        val sites = program.memory.blocks
            .filter { it.isExecute && it.isInitialized }
            .flatMap { block ->
                val bytes = ByteArray(block.size.toInt()).also { block.getBytes(block.start, it) }
                bytes.indices
                    .filter { jumpOverFillAt(bytes, it, block.start.offset) }
                    .map { block.start.add(it.toLong()) }
            }
            .filter { program.functionManager.getFunctionContaining(it) == null }
        assumeTrue(sites.isNotEmpty(), "Skipping: no jump-over-fill idiom in $binaryName")

        val uncollapsed = sites.filterNot { program.listing.getDataAt(it)?.dataType is AlignmentDataType }
        uncollapsed.take(10)
            .mustBeEmpty("${uncollapsed.size} of ${sites.size} jump-over-fill runs were left uncollapsed")
    }

