/**
 * Execution-order mode for the regression harness.
 *
 * The behavior of StabsAnalyzer can differ depending on whether it runs as
 * part of Ghidra's auto-analysis pass (alongside the demangler, decompiler,
 * etc.) or strictly after it. Both modes are observed in practice (e.g. when
 * a user re-imports stabs from the Tools menu after an analysis has settled).
 *
 *  - [CONCURRENT]: our analyzer is left enabled in the analysis options. It is
 *    fired by `AutoAnalysisManager.startAnalysis` alongside the demangler.
 *    Symptom: many function names stay mangled (`_Z6encodeP6Buffer` and the like),
 *    presumably because the demangler runs later but skips symbols whose
 *    SourceType we've already promoted.
 *
 *  - [AFTER]: our analyzer is disabled in the analysis options before
 *    `startAnalysis` runs, so auto-analysis (demangler included) settles
 *    first. We then invoke StabsAnalyzer manually. Symptom seen here:
 *    `/Demangler/...` placeholder stubs created by Ghidra's demangler are
 *    sometimes not replaced (e.g. `/Demangler/bouniaf`) — this was
 *    a DemanglerReplacer candidate-filtering bug, see DemanglerReplacer.
 */
enum class Mode { BEFORE, CONCURRENT, AFTER }

/**
 * Regression test harness for StabsAnalyzer, one subclass per fixture × [Mode] (generated by
 * `:generateFixtureTests` from the corpus on disk). Runs the full analysis pipeline and validates
 * the materialized output plus the counters against the fixture's committed baseline.
 *
 * **Every assertion here is corpus-wide.** Nothing may be gated on `binaryName`, and nothing may
 * look up a class only one binary declares: an assertion keyed to a fixture stops running the
 * moment that fixture is not on disk, silently. Drive the check from [ImportArtifacts.harvest] /
 * [ImportArtifacts.registry] instead, assert over every instance of the shape, and `assumeTrue` on
 * the shape being present at all.
 *
 * A fixture that is absent skips its whole class.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
@Tag("integration")
abstract class StabsImportRegressionBase(val binaryName: String, val mode: Mode) :
    AbstractGhidraHeadlessIntegrationTest() {

    // Manual inputs live under src/test/resources/ (binaries — gitignored,
    // user-placed — and baselines — tracked); test-generated dumps go to
    // build/test-output/ so `./gradlew clean` regenerates them. See README
    // / build.gradle.kts for the split rationale.
    private fun outputFile(kind: String) = File("build/test-output/${kind}s/${fixture.nameWithoutExtension}-$kind.json")
    private val fixture get() = File("src/test/resources/binaries/$binaryName")
    private val baselineFile get() = File("src/test/resources/baselines/${fixture.nameWithoutExtension}-baseline.json")
    private val recordsFile get() = outputFile("record")
    private val emptyStubDumpFile get() = File(
        "build/test-output/demangler-empty-stubs/${fixture.nameWithoutExtension}.txt",
    )
    private val harvestFile get() = outputFile("harvest.${mode.name.lowercase()}")
    private val registryDumpFile get() = outputFile("registry.${mode.name.lowercase()}")
    private val degradationFile
        get() = File("build/test-output/degradations/${fixture.nameWithoutExtension}.${mode.name.lowercase()}.txt")
    private val logFile
        get() = File("build/test-output/logs/${fixture.nameWithoutExtension}.${mode.name.lowercase()}.log")
    private val analysisTimesFile
        get() = File("build/test-output/analysis-times/${fixture.nameWithoutExtension}.${mode.name.lowercase()}.txt")

    private lateinit var loadResults: LoadResults<Program>
    private lateinit var context: ImportContext<CapturingSink>
    private lateinit var artifacts: ImportArtifacts
    private val program get() = context.program

    @BeforeAll
    fun setUp() {
        assumeTrue(
            fixture.exists(),
            "Skipping: ${fixture.path} absent, must be added manually",
        )

        val log = MessageLog()
        val monitor = TaskMonitor.DUMMY
        logFile.parentFile.mkdirs()
        recordsFile.parentFile.mkdirs()
        harvestFile.parentFile.mkdirs()

        try {
            // Loading the raw binary is the ONLY legitimately-skippable step: a corrupt or
            // format-unsupported fixture is an environment problem, not a bug in our analyzer.
            // Everything after it is code under test and must fail loudly (see the catch below).
            loadResults = try {
                ProgramLoader.builder().source(fixture).compiler("gcc").log(log).monitor(monitor).load()
            } catch (e: Exception) {
                e.printStackTrace()
                abort("Skipping $binaryName: ProgramLoader could not load the fixture: $e")
            }

            context = loadResults.getPrimaryDomainObject(this).defaultContext()

            val mgr = AutoAnalysisManager.getAnalysisManager(program)
            val options = program.getOptions(Program.ANALYSIS_PROPERTIES)

            when (mode) {
                Mode.CONCURRENT -> {
                    // Confirm Ghidra's ClassSearcher actually discovered our analyzer
                    // (build/classes/kotlin/main is on the test classpath). If this
                    // assertion ever fails the test would be silently meaningless.
                    val discovered = mgr.getAnalyzer(StabsAnalyzer.NAME)
                    discovered.mustNotBeNull("StabsAnalyzer not discovered by ClassSearcher")
                    discovered.mustBeA<StabsAnalyzer>()

                    // Pre-build the test's context and install its CapturingSink as a
                    // side-channel on the Program. StabsAnalyzer.added() will tee its
                    // output to that sink in addition to Ghidra's truncating MessageLog,
                    // so we get the full, untruncated log here while autoanalysis still
                    // sees its own logs in MessageLog.
                    val probe = ImportProbe.install(context)

                    // BYTE_ANALYZER auto-fires on byte changes; on a freshly-loaded
                    // program nothing has "changed" since the loader put
                    // bytes down, so we explicitly schedule our analyzer for the
                    // next analysis pass — it then runs at its declared priority
                    // alongside the demangler.
                    // Sub-options writes hit the program options DB and need a transaction (as the
                    // AFTER branch's analyzer-disable does); the .stab overlay is a diagnostic view,
                    // not needed to produce types (~8% of the run), so skip it here too.
                    program.runTransaction("enable-stabs-analyzer") {
                        options.setBoolean(StabsAnalyzer.NAME, true)
                        options.getOptions(StabsAnalyzer.NAME)[OVERLAY_SECTION] = false
                    }
                    mgr.scheduleOneTimeAnalysis(discovered, program.memory)
                    runAutoAnalysis(mgr, monitor)
                    artifacts = checkNotNull(probe.artifacts) { "artifacts not populated by CONCURRENT" }
                }

                Mode.BEFORE -> {
                    // Just run our analyzer with no autoanalysis
                    program.runTransaction("stabs-analyze") {
                        artifacts = checkNotNull(context.import().artifacts) { "artifacts not populated by BEFORE" }
                    }
                }

                Mode.AFTER -> {
                    // Disable our analyzer so auto-analysis (incl. demangler) settles
                    // without us, then re-run it manually with our CapturingSink.
                    // `Options.setBoolean` mutates the program options DB and needs
                    // a transaction.
                    program.runTransaction("disable-stabs-analyzer") {
                        options.setBoolean(StabsAnalyzer.NAME, false)
                    }
                    mgr.initializeOptions()
                    runAutoAnalysis(mgr, monitor)
                    program.runTransaction("stabs-analyze") {
                        artifacts = checkNotNull(context.import().artifacts) { "artifacts not populated by AFTER" }
                    }
                }
            }
            // CapturingSink holds the full untruncated log in both modes
            // (in CONCURRENT it's fed via ExternalSinks → TeeSink). MessageLog
            // is appended for parity with Ghidra's own view, even though it
            // truncates at ~500 lines.
            logFile.writeText(context.terminal.dedupedOutput() + "\n--- MessageLog ---\n" + log.toString())
            // Stripped/no-stabs fixtures produce no artifacts; nothing to dump.
            artifacts.writeRegistryDump(registryDumpFile)
            writeDegradationDump()
        } catch (e: org.opentest4j.TestAbortedException) {
            throw e // the load-failure skip above — propagate as a skip, not a failure
        } catch (e: Exception) {
            // Load succeeded, so anything thrown here is a bug in our import / analysis / dump path.
            // Fail the invocation loudly (in this exact fixture×mode) instead of masking it as a skip:
            // silently swallowing crashes here is what let a TypeResolver NPE and a registry-dump
            // `.single()` crash hide for so long, and dropped whole AFTER-mode runs unnoticed.
            e.printStackTrace()
            throw AssertionError("setUp failed for $binaryName/$mode (import/dump, not fixture load): $e", e)
        }
    }

    private fun runAutoAnalysis(mgr: AutoAnalysisManager, monitor: TaskMonitor) {
        program.disableWindowsResourceAnalyzer()
        mgr.reAnalyzeAll(null)
        program.runTransaction("auto-analyze") {
            mgr.startAnalysis(monitor)
            mgr.waitForAnalysis(null, monitor)
        }
        // Ghidra's own per-analyzer wall times. The Gradle listener only reports whole-invocation
        // time, which also carries fixture load, our import and the dumps; this attributes the
        // analysis share to individual analyzers, so a perf change can be localized without a
        // profiler. Written per fixture×mode alongside the other dumps.
        analysisTimesFile.apply { parentFile.mkdirs() }
            .writeText("total = ${mgr.totalTimeInMillis} ms\n\n${mgr.taskTimesString}")
    }

    // The CLI's `--degradation-log` dump, grouped by category, so one integrationTest run emits the
    // full CLI dump set (records/harvest/registry already written above) without a separate probe pass.
    private fun writeDegradationDump() {
        val byCategory = context.diagnostics.snapshotDegradations()
            .groupBy { it.category }.toList().sortedByDescending { it.second.size }
        degradationFile.parentFile.mkdirs()
        degradationFile.writeText(
            buildString {
                appendLine("fixture: $binaryName ($mode)")
                appendLine("total degradations: ${byCategory.sumOf { it.second.size }}")
                appendLine("\ncounts by category:")
                byCategory.forEach { (cat, list) -> appendLine("  $cat = ${list.size}") }
                byCategory.forEach { (cat, list) ->
                    appendLine("\n=== $cat (${list.size}) ===")
                    list.forEach { appendLine("  ${it.detail}") }
                }
            },
        )
    }

    @AfterAll
    fun tearDown() {
        ImportProbe.clear(program)
        program.release(this)
        loadResults.close()
    }

    @Test
    fun countersWithinBaseline() {
        assumeTrue { mode == Mode.AFTER || mode == Mode.CONCURRENT }
        // Authoritative per-category counts. Not `log.tagFrequencies()`: that only sees categories
        // that reach the sink (record*/direct-inc bypass it) and ignores `count = n` tallies, which
        // made assertions on those categories (e.g. empty-scope) silently vacuous.
        val counters = context.diagnostics.snapshotCounters()

        // -PregenerateBaselines=true rewrites the baseline from the observed counts (deterministic
        // import). The resulting git diff is the record of exactly which counters moved. This has to
        // precede the exists() check below, or a newly added fixture can never get a first baseline:
        // the assumption skips the test before it can write one.
        if (System.getProperty("regenerateBaselines") == "true") {
            BaselineWriter.write(baselineFile, counters, "$binaryName - generated from snapshotCounters()")
            return
        }

        assumeTrue(baselineFile.exists(), "Skipping: no committed baseline for $binaryName")

        val baseline = BaselineLoader.load(baselineFile)

        // If no stabs were found in the binary, skip the test
        // (stabs sections may not exist or may be in a non-standard format)
        assumeTrue(
            counters.isNotEmpty(),
            "Skipping: No stabs counters found in binary (stabs sections absent or non-standard format)",
        )

        val drift = mutableListOf<String>()
        for ((counterName, range) in baseline.counters) {
            val actual = counters.getOrDefault(counterName, 0L)
            if (actual !in range.min..range.max) {
                drift += "Counter '$counterName' = $actual outside baseline range [${range.min}..${range.max}]"
            }
        }
        if (drift.isNotEmpty()) {
            Assertions.fail<Unit>("Baseline drift detected:\n  - " + drift.joinToString("\n  - "))
        }
    }

    /**
     * Every array global lands with the element count its stab declares. gcc encodes the count only
     * via the index Range (`ar(0,1);0;15;`), never as a length, and the old Array case bailed
     * whenever either the element Ref failed to resolve or the length was absent — leaving the
     * global untyped. [ghistabs.materialize.DataTypeRegistry] now derives the count from the Range and
     * falls back to Undefined1 elements.
     *
     * Driven from the harvest rather than a named symbol, so it covers every array global in every
     * fixture. Must hold in both modes: CONCURRENT races autoanalysis's `undefined4` placeholders,
     * which `applyGlobalOrStatic` evicts via `DataUtilities.CLEAR_ALL_CONFLICT_DATA`.
     */
    @Test
    @ExpectedToFail(
        fixtures = ["zlib_aout_gcc263.o", "tinyxml_aout_gcc295.o"],
        reason = "relocatable object (ld -r): sections sit at 0 unrelocated, so a global's stab value " +
            "resolves into a block with nothing applied at it — gcc 2.95's `__vt_<class>` vtables on " +
            "tinyxml are array globals and land there",
    )
    fun arrayGlobalsGetTheirDeclaredLength() {
        val declared = artifacts.harvest.staticsByCu.values.flatten()
            .mapNotNull { sym ->
                val elements = (resolve(sym.body.type) as? TypeDecl.Array)?.declaredElements ?: return@mapNotNull null
                val addr = context.resolver.buildAddress(sym.rawValue)
                Triple(sym.body.name, addr, elements).takeIf { program.memory.getBlock(addr) != null }
            }
        assumeTrue(declared.isNotEmpty(), "Skipping: no array globals with a declared extent")

        val applied = declared.mapNotNull { (name, addr, elements) ->
            (program.listing.getDataAt(addr)?.dataType as? Array)?.let { Triple(name, it, elements) }
        }
        val untyped = declared
            .filterNot { (_, addr, _) -> program.listing.getDataAt(addr)?.dataType is Array }
            .map { (n, a, _) -> "$n @ $a is ${program.listing.getDataAt(a)?.dataType?.name}" }
        val wrong = applied.filter { (_, arr, elements) -> arr.numElements.toLong() != elements }
            .map { (name, arr, elements) -> "$name: ${arr.numElements} elements, stab says $elements" }
        // The count is only half of it: the old Array case also bailed when the element Ref failed to
        // resolve, and `Undefined1` elements are the fallback that silently hides that. An element the
        // stab names as an aggregate or enum must come through as one.
        val undefinedElements = declared.mapNotNull { (name, addr, _) ->
            val declaredElement = (
                resolve(
                    artifacts.harvest.staticsByCu.values.flatten()
                        .first { it.body.name == name }.body.type,
                ) as? TypeDecl.Array
                )?.element
            val named = (resolve(declaredElement ?: return@mapNotNull null) as? TypeDecl.Struct) != null ||
                (resolve(declaredElement) as? TypeDecl.Enum) != null
            val applied = program.listing.getDataAt(addr)?.dataType as? Array ?: return@mapNotNull null
            "$name: elements are ${applied.dataType.name}".takeIf { named && applied.dataType is Undefined }
        }
        assertAll(
            {
                untyped.sorted().take(
                    10,
                ).mustBeEmpty("${untyped.size} of ${declared.size} declared array globals never became an Array")
            },
            {
                wrong.take(10).mustBeEmpty("${wrong.size} of ${applied.size} array globals lost their declared extent")
            },
            {
                undefinedElements.take(
                    10,
                ).mustBeEmpty("${undefinedElements.size} array globals fell back to Undefined elements")
            },
        )
    }

    /**
     * The program's line map is the harvest's, entry for entry: [ghistabs.importer.SourceMapApplier]
     * counts what it should hold from the parsed entries (distinct after the §15 fold, minus the ones
     * it reported dropping), and the database is read back to see that it does. An entry lost to a
     * silently-swallowed rejection shows up here as a shortfall.
     *
     * Both counters, because the applier writes two kinds of entry onto the one manager: the
     * zero-length N_SLINE points and the ranged N_SO/N_SOL text partition.
     *
     * Also the fold's own contract: a spelling folded away keeps its `SourceFile`, with no entries.
     */
    @Test
    fun programLineMapMatchesHarvest() {
        val folds = artifacts.index.renderIdentityBySource
        assumeTrue(folds.isNotEmpty(), "Skipping: no N_SLINE entries in this binary")
        val manager = program.sourceFileManager
        val counters = context.diagnostics.snapshotCounters()
        val expected = counters.getOrDefault("sourcemap-entries", 0) + counters.getOrDefault("textrange-entries", 0)

        manager.allSourceFiles.sumOf {
            manager.getSourceMapEntries(it).size
        }.toLong().mustBe(expected, "source map entries in the program")
        manager.allSourceFiles.must(
            "every spelling and every fold target must be listed: missing " +
                ((folds.keys + folds.values) - manager.allSourceFiles.toSet()).map {
                    it.path
                },
        ) { containsAll(folds.keys + folds.values) }
        for ((raw, target) in folds) {
            if (raw == target) continue
            manager.getSourceMapEntries(
                raw,
            ).size.mustBe(0, "${raw.path} folded onto ${target.path} must keep no entries")
        }
    }

    /**
     * The query a listing field makes — "what line is this address in" — against a map of points.
     * Both halves have to hold: an entry sits at exactly the address the harvest gave it, and an
     * address mid-statement walks back to the statement it is inside
     * (`getSourceMapEntryIterator(addr, false)`, since a zero-length entry answers `getSourceMapEntries`
     * only at its own address).
     *
     * Addresses outside a defined block are excluded — those are the entries the applier reports
     * dropping, so including them would assert that a reported failure did not happen.
     */
    @Test
    fun addressesResolveToTheirEntries() {
        val manager = program.sourceFileManager
        // Folded: that is the identity the entries were transferred onto.
        val entries = artifacts.index.functions.flatMap { it.lineEntries }
            .filter { program.memory.getBlock(it.addr) != null }
        assumeTrue(entries.isNotEmpty(), "Skipping: no N_SLINE entries in this binary")

        val missing = entries.filterNot { e ->
            manager.getSourceMapEntries(e.addr).any { it.sourceFile == e.source && it.lineNumber == e.line }
        }
        missing.take(5).map {
            "${it.source.filename}:${it.line} @ ${it.addr}"
        }.mustBeEmpty(
            "${missing.size} of ${entries.size} line entries are absent from the program at their own address",
        )

        // Every published address, so the predecessor of the gap really is a predecessor.
        val addresses = artifacts.harvest.lineEntries.values.asSequence().flatten()
            .map { it.addr }.filter { program.memory.getBlock(it) != null }.distinct().sorted().toList()
        val (statement, inside) = addresses.zipWithNext()
            .firstNotNullOfOrNull { (a, b) ->
                (b.offset - a.offset).takeIf { it > 1 && a.hasSameAddressSpace(b) }?.let { a to a.add(it / 2) }
            } ?: return
        manager.getSourceMapEntryIterator(
            inside,
            false,
        ).firstOrNull()?.baseAddress.mustBe(statement, "walking back from $inside, mid-statement")
    }

    /**
     * A root becomes directory transforms on the program, and [LocalSources] reads back through them —
     * with the guard that a file whose content disagrees with what the harvest filed there is not the
     * file this binary was built from, however well its path resolved.
     *
     * The tree is built to match one of the program's own recorded directories, so this exercises the
     * fixture's real spellings (drive letters, `c++` segments) rather than invented ones.
     */
    @Test
    fun sourceRootRegistersTransformsAndGuardsAgainstTheWrongTree(@TempDir root: Path) {
        val source = program.sourceFileManager.allSourceFiles
            .firstOrNull { it.path.count { c -> c == '/' } > 1 }
            ?: abort("Skipping: no recorded source with a directory")
        val recordedDir = source.path.removeSuffix(source.filename)
        val local = root.resolve(recordedDir.split('/').last { it.isNotEmpty() })
            .resolve(source.filename)
        local.parent.createDirectories()
        local.writeText("// 1\n// 2\nclass Widget {};\nclass Gadget {};\nclass Sprocket {};\n")

        program.applySourceRoots(listOf(root), context)

        // Three claims at least, or the file is not judged at all — one misfiled declaration must not
        // be able to discard a correctly mapped file.
        val claims = listOf(
            Type.Decl(3, "Widget"),
            Type.Decl(4, "Gadget"),
            Type.Decl(5, "Sprocket"),
        )
        val agreeing = LocalSources(program, context) { claims }
        agreeing[source].mustBe(local.toFile(), "transform should resolve to the local file")

        val disagreeing = LocalSources(program, context) { claims.map { it.copy(line = it.line + 30) } }
        disagreeing[source].mustBeNull("a file that does not carry the claim must be dropped")
        context.diagnostics.snapshotCounters().getOrDefault("source-root-mismatch", 0L).must(
            "the drop must be reported",
        ) { this > 0 }
    }

    /**
     * A static member function takes no `this`. The stabs flag it `?` in the method-block trailer,
     * and parsing that as pure-virtual made ClassBuilder treat every one as an instance method:
     * forced __thiscall, injected a phantom `<Class> *this`, and replaced the N_PSYM params with the
     * empty list the `f(ret)` signature carries.
     *
     * Every `STATIC`-flagged method the harvest resolved to an address. Two halves, because they
     * broke separately: the declared parameters must survive, and no `this` may be injected
     * alongside them. The second half only ever failed under auto-analysis, because the injection
     * is Ghidra's: the demangler cannot tell a static member from an instance one and applies
     * `__thiscall` to both. Hence the convention in the failure message — it is the diagnosis.
     */
    @Test
    fun staticMethodsTakeNoThis() {
        val statics = staticMethodsByMangledName()
        assumeTrue(statics.isNotEmpty(), "Skipping: no static member functions in this fixture")
        // A nullary static (`…Ev`, the Itanium spelling of an empty parameter list) has nothing to
        // lose, so only the ones the mangling says take arguments can show the params-replaced half.
        val stripped = statics.filterKeys { !it.endsWith("Ev") }.values
            .filter { f -> f.parameters.none { it.name != "this" && it.name != "__return_storage_ptr__" } }
            .filter { f -> f.parameters.any { it.name == "this" } }
        val injected = statics.values.filter { f -> f.parameters.any { it.name == "this" } }
        fun render(fs: Collection<Function>) = fs.map { f ->
            val params = f.parameters.joinToString { it.name }
            "[${f.callingConventionName}] ${f.parentNamespace.name}::${f.name}($params)"
        }
        assertAll(
            {
                render(stripped).take(10).mustBeEmpty(
                    "${stripped.size} of ${statics.size} static member functions kept only an injected " +
                        "`this` — their declared parameters were replaced",
                )
            },
            {
                render(
                    injected,
                ).take(
                    10,
                ).mustBeEmpty("${injected.size} of ${statics.size} static member functions were given a `this`")
            },
        )
    }

    /**
     * A class whose only Itanium symbols are static data members still lands in its real namespace.
     * `ensureClassNamespace` read the chain off a *method's* mangled name, so `std::ctype_base` —
     * which declares no member functions at all, only `alnum`/`alpha`/`digit`/… — fell back to the
     * source-form leaf and was built as a root-level `ctype_base`. Its members' linkage names
     * (`_ZNSt10ctype_base5alnumE`) carry the same chain.
     */
    @Test
    fun constantsOnlyClassLandsInItsNamespace() {
        val cls = program.symbolTable.getSymbols("ctype_base")
            .firstOrNull { it.symbolType == ghidra.program.model.symbol.SymbolType.CLASS }
        assumeTrue(cls != null, "Skipping: ctype_base class namespace absent")
        cls!!.parentNamespace.name.mustBe(
            "std",
            "ctype_base sits under '${cls.parentNamespace.getName(true)}' — the class's namespace " +
                "chain was not recovered from its static members' linkage names",
        )
    }

    /**
     * A 1-byte bool global occupies 1 byte, and its neighbor is reachable.
     *
     * Without `-gstabs+` gcc spells `bool` as an enum over False/True (`gcc/dbxout.c`), losing the
     * width; as a sizeof(int) enum it swallowed the three globals after it, so five of CryptoPP's
     * eight adjacent `g_has*` flags had no data of their own — `createData` returns the containing
     * item as a success, so nothing threw.
     */
    @Test
    fun adjacentBoolGlobalsEachOwnTheirByte() {
        val flags = listOf("_ZN8CryptoPP9g_hasISSEE", "_ZN8CryptoPP9g_hasSSE2E", "_ZN8CryptoPP10g_hasSSSE3E")
            .mapNotNull { n ->
