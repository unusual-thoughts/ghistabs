    /**
     * Every slot [ghistabs.harvest.HarvestIndex.byLocation] declares is filled, at the path it declared.
     *
     * That map *is* the contract: `TypeRegistry` seeds and materializes each group at exactly
     * `(location.category, location.name)`, so it is the pipeline's own statement of what the DTM
     * should contain — which makes this exact, with no name normalization and no re-derivation of
     * attribution or shortening. Three separate things can go wrong and each is reported on its own:
     *
     *  1. **The type never materialized.** gcc reuses local type ids inside BINCL blocks, so several
     *     distinct types canonicalize onto one [GlobalTypeId]; before 4b21a6c the loser of that
     *     collision was dropped and its name went with it.
     *  2. **It landed somewhere else.** Attribution and the content-hash dedup have to agree on one
     *     category, or `ClassBuilder` cannot find the type it just built.
     *  3. **It is an empty stub.** A group whose winner has a body must not resolve to a
     *     zero-component Structure — the whole group is then unusable however well it was filed.
     *  4. **Two slots resolved onto one type.** Then one of the two names is simply not in the DTM,
     *     which is how the BINCL collision in (1) actually shows itself: three unrelated classes on
     *     one id, one DataType, two names gone. Distinct slots keep distinct types — measured at
     *     zero across the corpus, so it is assertable as zero.
     */
    @Test
    fun everyDeclaredSlotIsFilledWhereItWasDeclared() {
        val slots = artifacts.index.byLocation
        assumeTrue(slots.isNotEmpty(), "Skipping: no located types in this fixture")

        val applied = slots.map { (location, located) ->
            Triple(location, located, artifacts.registry.dataTypeFor(located.type.id))
        }
        fun report(of: List<String>) = of.sorted().take(10)

        val absent = applied.filter { (_, _, dt) -> dt == null }
            .map { (location, located) -> "$location (winner ${located.type.id})" }
        val misfiled = applied.mapNotNull { (location, _, dt) ->
            dt?.takeIf { it.categoryPath != location.category }?.let { "$location materialized at ${it.pathName}" }
        }
        val merged = applied.filter { (_, _, dt) -> dt != null }
            .groupBy({ it.third }, { it.first })
            .filterValues { it.size > 1 }
            .map { (dt, locations) -> "${dt?.pathName} claimed by ${locations.sortedBy { l -> l.toString() }}" }
        val hollow = applied.mapNotNull { (location, located, dt) ->
            val declared = (located.type.body as? TypeDecl.Struct)?.hasMembers == true
            "$location is an empty ${dt?.javaClass?.simpleName}"
                .takeIf { declared && (dt as? Composite)?.numComponents == 0 }
        }
        // Enums are not Composites, so `hollow` cannot see them: a named enum that materialized as
        // an empty Structure, or as an Enum with no values, is the same defect in the other kind.
        // (`exprInstHasComponents` checked exactly this for one enum on one binary.)
        val flatEnums = applied.mapNotNull { (location, located, dt) ->
            val members = (located.type.body as? TypeDecl.Enum)?.members?.size ?: return@mapNotNull null
            "$location declares $members values, materialized as ${dt?.javaClass?.simpleName}"
                .takeIf { members > 0 && (dt as? Enum)?.count?.let { it > 0 } != true }
        }
        assertAll(
            { report(absent).mustBeEmpty("${absent.size} declared slots never materialized") },
            { report(misfiled).mustBeEmpty("${misfiled.size} slots materialized off their declared category") },
            { report(hollow).mustBeEmpty("${hollow.size} slots with a declared body are empty stubs") },
            { report(merged).mustBeEmpty("${merged.size} DataTypes are claimed by more than one slot") },
            {
                report(
                    flatEnums,
                ).mustBeEmpty("${flatEnums.size} declared enums materialized without their values")
            },
        )
    }

    /**
     * A derived class carries its base subobject. Either shape counts:
     *  - a named `_base_…` / `_vbase_…` component, when the base type resolved;
     *  - the struct's first own field at offset > 0, the base bytes left as bare Undefined1 — the
     *    explicit "don't pretend we know what's here" choice, taken when the base's own stabs body
     *    is absent (libstdc++ classes reached only through iosfwd's forward declaration).
     *
