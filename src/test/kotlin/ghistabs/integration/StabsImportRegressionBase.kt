    /**
     * A register local lands in the register its stab names. The number is the record's n_value —
     * `w:r(0,5)` carries no register in the descriptor — and `readTrailingReg()` used to return a
     * hardcoded 0, so every register local in every fixture was placed in dbx 0 = EAX. Nothing
     * caught it: `reglocal-unmapped-regnum` can't fire when the number is always mappable.
     *
     * Checked over every register local the harvest recorded, so no fixture has to declare a
     * particular function. Ghidra narrows the storage to the variable's own width (a 2-byte local in
     * EDI is stored as `DI`), so the assertion is on the containing register, not the exact spelling.
     * Register locals shadowing a parameter name never reach the program (`reglocal-skipped-dup-param`)
     * and simply do not appear in the map being compared.
     */
    @Test
    fun registerLocalsUseTheirStabsRegister() {
        val declared = artifacts.harvest.functions.flatMap { func ->
            // Only names that occur once in the function. gcc emits one record per lexical block, so a
            // function can declare `__s1` twice in two blocks and hold it in a different register each
            // time (`_M_mutate` does exactly that, EAX/EDX and back). There is no name to pair those
            // against a single Ghidra local by, and pairing both against the first match reports the
            // swap as two failures — 287 functions on crypto_mi_test alone.
            val once = func.locals.filter { it.body.location == VariableLocation.REGISTER }
                .groupBy { it.body.name }.filterValues { it.size == 1 }.values.map { it.single() }
            once.mapNotNull { local ->
                val want = dbxRegisterName(program.defaultPointerSize, local.rawValue.toInt())
                    ?: return@mapNotNull null
                Triple(func, local.body.name, want)
            }
        }
        assumeTrue(declared.isNotEmpty(), "Skipping: no mappable register locals in this fixture")

        val checked = declared.mapNotNull { (func, name, want) ->
            val applied = program.functionManager.getFunctionAt(func.addr)
                ?.localVariables
                // ambiguous on Ghidra's side too — nothing to pair against
                ?.singleOrNull { it.name == name && it.variableStorage.isRegisterStorage }
                ?: return@mapNotNull null
            val got = applied.variableStorage.registers.single()
            Triple("${func.name}:$name", want, generateSequence(got) { it.parentRegister }.map { it.name }.toList())
        }
        assumeTrue(checked.isNotEmpty(), "Skipping: no register local reached the program")
        val wrong = checked.filterNot { (_, want, got) -> want in got }
            .map { (where, want, got) -> "$where: stab says $want, applied to ${got.first()}" }
        wrong.take(10).mustBeEmpty(
            "${wrong.size} of ${checked.size} register locals ignored their stab's n_value " +
                "(all landing in one register means the number was lost)",
        )
    }

