package ghistabs.build

import org.gradle.api.Project
import org.gradle.api.file.DuplicatesStrategy
import org.gradle.api.file.RegularFile
import org.gradle.api.provider.Provider
import org.gradle.api.tasks.JavaExec
import org.gradle.api.tasks.SourceSetContainer
import org.gradle.api.tasks.bundling.Jar
import org.gradle.api.tasks.bundling.Zip
import org.gradle.kotlin.dsl.get
import org.gradle.kotlin.dsl.getByType
import org.gradle.kotlin.dsl.register
import java.io.File
import kotlin.io.path.Path
import kotlin.io.path.relativeTo

const val CLI_MAIN = "ghistabs.cli.MainKt"

// The CLI has its own source set so neither it nor clikt land on the main runtimeClasspath, which is
// what the extension zip's lib/ is built from.
val Project.sourceSets get() = extensions.getByType<SourceSetContainer>()
val Project.cli get() = sourceSets["cli"]

// No `-Djdk.serialFilterFactory` unlike the test harness: HeadlessGhidraApplicationConfiguration
// installs Ghidra's factory itself, and setting both throws "filter factory already instantiated".
val CLI_JVM_ARGS = GHIDRA_JVM_ARGS + listOf("-Xmx2g", "--enable-native-access=ALL-UNNAMED")

// Run the CLI in-process against the `cli` runtime classpath (Ghidra jars + main output + clikt).
// Pass args with `-Pargs="skeleton <binary> -d out"`.
fun Project.registerRunCli() = tasks.register<JavaExec>("runCli") {
    group = "application"
    description = "Run the headless skeleton/decomp CLI ($CLI_MAIN)"
    dependsOn(cli.classesTaskName)
    classpath = cli.runtimeClasspath
    mainClass.set(CLI_MAIN)
    jvmArgs(CLI_JVM_ARGS)
    args = providers.gradleProperty("args").getOrElse("").split(" ").filter { it.isNotEmpty() }
}

/**
 * Fat CLI JAR, contains all depenedencies except ghidra
 */
fun Project.registerCliJar() = tasks.register<Jar>("cliJar") {
    description = "Generate the JAR for headless skeleton/decomp CLI"
    archiveBaseName.set("ghidra-stabs-cli")
    duplicatesStrategy = DuplicatesStrategy.EXCLUDE
    manifest {
        attributes(mapOf("Main-Class" to CLI_MAIN))
    }
    from(sourceSets["main"].output, cli.output)
    from(
        cli.runtimeClasspath.files.filter { !it.toPath().startsWith(ghidraInstallDir) }.mapNotNull {
            when {
                it.isDirectory -> it
                it.isFile -> zipTree(it)
                else -> null
            }
        },
    )
}

/**
 * Standalone launcher at `build/libs/ghidra-stabs` that runs the fat CLI JAR at `build/libs/ghidra-stabs.jar`
 * and builds the classpath with ghidra's jars
 */
fun Project.registerBuildCliScript() = tasks.register("buildCli") {
    group = "application"
    description = "Generate a standalone launcher script for the CLI at build/cli/ghidra-stabs"
    val script = layout.buildDirectory.dir("libs").map { it.file(("ghidra-stabs")) }
    val runtimeClasspath = cli.runtimeClasspath
    val ghidraRoot = ghidraInstallDir // resolved here: doLast must not capture the Project
    outputs.file(script)
    doLast {
        val ghidraJars = runtimeClasspath.files.filter { it.toPath().startsWith(ghidraRoot) }

        val classpath = ghidraJars
            .map { Path($$"$GHIDRA_INSTALL_DIR").resolve(it.toPath().relativeTo(ghidraRoot)) }
            .joinToString(":")

        script.get().asFile.apply {
            writeText(
                buildString {
                    appendLine("#!/bin/sh")
                    appendLine("# Generated by `gradle buildCli`. lib/ is self-contained.")
                    appendLine("GHIDRA_INSTALL_DIR=\"\${GHIDRA_INSTALL_DIR:-$ghidraRoot}\"")
                    appendLine($$"dir=$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd)")
                    appendLine("exec java ${CLI_JVM_ARGS.joinToString(" ")} \\")
                    appendLine($$"  -cp \"$dir/ghidra-stabs-cli.jar:$$classpath\" \\")
                    appendLine("  $CLI_MAIN \"$@\"")
                },
            )
            setExecutable(true)
        }
    }
}

fun Project.registerZipCli(cliJar: Provider<RegularFile>, scriptFile: Provider<File>) = tasks.register<Zip>("zipCli") {
    inputs.file(cliJar)
    archiveFileName.set("ghidra-cli.zip")
    destinationDirectory.set(layout.projectDirectory.dir("dist"))
    from(cliJar, scriptFile)
}

fun Project.registerCli() = registerZipCli(
    registerCliJar().flatMap { it.archiveFile },
    registerBuildCliScript().map { it.outputs.files.singleFile },
)
