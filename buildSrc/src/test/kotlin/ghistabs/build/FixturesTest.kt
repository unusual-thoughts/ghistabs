package ghistabs.build

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * [Fixtures.className] names files that are written to disk and then compiled, so a change here
 * silently orphans the task filters and the progress listener rather than failing anything.
 *
 * Names here are invented, not read from the corpus: this is pure string logic, and a unit test that
 * hard-codes real fixture filenames breaks whenever the corpus changes.
 */
class FixturesTest {
    private val corpus = listOf("one_sample.exe", "two_sample", "three_sample_v2.o")

    @Test
    fun classNameCamelCasesEverySeparator() {
        assertEquals("OneSampleExeConcurrentTest", Fixtures.className("one_sample.exe", "CONCURRENT"))
        assertEquals("TwoSampleAfterTest", Fixtures.className("two_sample", "AFTER"))
        assertEquals("ThreeSampleV2OAfterTest", Fixtures.className("three_sample_v2.o", "AFTER"))
    }

    @Test
    fun noFiltersMeansEveryFixtureInTheDefaultMode() {
        val f = Fixtures(corpus)
        assertFalse(f.regressionOnly, "no -Pregression means the run is not the matrix alone")
        assertEquals(Fixtures.DEFAULT_MODES, f.selectedModes)
        assertEquals(corpus.size, f.plannedTotal)
        // Labels stay whole-corpus: the listener has to recognise any suite the run happens to emit.
        assertEquals(corpus.size * Fixtures.MODES.size, f.labels.size)
        // The other two modes are subtracted, so the behavioural classes keep running.
        assertEquals(corpus.size * (Fixtures.MODES.size - 1), f.unselectedModeClasses.size)
    }

    @Test
    fun regressionNarrowsTheSuiteAndModeNarrowsTheMatrix() {
        val f = Fixtures(corpus, regressionFilter = " two_sample , one_sample.exe ", modeFilter = "before")
        assertTrue(f.regressionOnly)
        assertEquals(2, f.plannedTotal)
        assertEquals(
            listOf("ghistabs.fixtures.TwoSampleBeforeTest", "ghistabs.fixtures.OneSampleExeBeforeTest"),
            f.selectedClasses,
        )
        assertEquals(corpus.size * (Fixtures.MODES.size - 1), f.unselectedModeClasses.size)
    }

    @Test
    fun bareRegressionIsEveryFixture() {
        val f = Fixtures(corpus, regressionFilter = "")
        assertTrue(f.regressionOnly, "-Pregression with no value still means the matrix alone")
        assertEquals(corpus, f.selectedBinaries)
    }

    @Test
    fun modeAllRestoresTheWholeMatrix() {
        val f = Fixtures(corpus, modeFilter = "all")
        assertEquals(Fixtures.MODES, f.selectedModes)
        assertEquals(emptyList<String>(), f.unselectedModeClasses)
    }

    @Test
    fun modesAreCommaSeparatedAndDeduplicated() {
        val f = Fixtures(corpus, modeFilter = "after, BEFORE ,after")
        assertEquals(listOf("AFTER", "BEFORE"), f.selectedModes)
    }

    @Test
    fun blankFiltersAreNotNarrowing() {
        val f = Fixtures(corpus, modeFilter = "  ,  ")
        assertEquals(Fixtures.DEFAULT_MODES, f.selectedModes)
    }
}

/** The generated files have to compile and satisfy ktlint, so their exact text is worth pinning. */
class FixtureTestSourceTest {
    @Test
    fun shortNamesStayOnOneLine() {
        val src = fixtureTestSource("one_sample.exe", "AFTER")
        assertTrue(
            src.contains("class OneSampleExeAfterTest : StabsImportRegressionBase(\"one_sample.exe\", Mode.AFTER)"),
        )
        assertTrue(src.startsWith("// GENERATED by"))
        assertTrue(src.endsWith("\n"))
    }

    @Test
    fun overlongDeclarationsWrapTheSuperType() {
        // ktlint's 120-col limit: the class declaration alone overruns it for a name this long.
        val src = fixtureTestSource("a_very_long_sample_name_that_will_not_fit_on_one_line_at_all.exe", "CONCURRENT")
        assertTrue(src.contains(":\n    StabsImportRegressionBase("), "expected the super type to wrap")
        assertTrue(src.lines().all { it.length <= 120 }, "generated a line ktlint would reject")
    }
}
